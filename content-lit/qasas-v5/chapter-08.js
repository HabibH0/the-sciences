//      نَهْر، أَكَلَ، مِنْ، شَجَر، نَحَتَ، جَبَل، بَيْت، كَانَ، ذَلِكَ، لَا، يَكُونُ (from
//      كَانَ)، لِمَاذَا، مَاتَ، أَب، لَهُمْ (from لِ)، كَذَلِكَ، عَيْن، لَكِنَّ، كُلّ،
//      لَمْ، نَفَعَ، مَنَعَ، وَصَلَ، إِلَيْهِمْ (from إِلَى)، مَلَك، مَوْت، وَجَدَ، سَبِيل،
