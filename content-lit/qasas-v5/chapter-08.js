// Ṣāliḥ keeps advising his people with wisdom and gentleness: he confronts
// them with a rhetorical volley -- do they think their palaces, gardens,
// crops, and rock-cut houses will last forever? -- then points to their own
// fathers, who had every one of those things and still died, none of it
// having benefited or protected them from the angel of death. He closes by
// warning his own generation of the same fate: they too will die, be raised,
// and be questioned about this abundance.
//
// Grammar / lexical notes:
//   -- وَلَمْ يَزَلْ صَالِحٌ يَنْصَحُ (qs-v5-c08-001) is a كَانَ-sister
//      construction: لَمْ يَزَلْ ("did not cease [to]") takes صَالِحٌ as its
//      nominative اسم and the verbal sentence يَنْصَحُ لِقَوْمِهِ... as its
//      خبر, parallel to the plain كَانَ + imperfect-predicate pattern
//      already established in ch1 (فَكَانُوا يَنْحِتُونَ). لَمْ and يَزَلْ are
//      tagged as two separate tokens, matching how لَمْ يَعْقِلُوا was split
//      in qasas-v3 ch16.
//   -- The bare vocative يَا إِخْوَانِي! at the head of qs-v5-c08-003 has no
//      predicate of its own, so per house convention (a vocative glued to
//      what follows) it is kept in the SAME sentence entry as the question
//      that follows it, despite the printed ! -- exactly the "يَا صَالِحُ"
//      case named in the shared brief. إِخْوَانِي (qs-v5-c08-003/012) is
//      tagged 'pl.acc+1s': grammatically a مُنَادًى مُضَاف takes the
//      accusative even though the ending is not visibly distinct here,
//      matching this volume's established practice of tagging invisible
//      case (cf. ثَمُودَ, ch1) rather than leaving it out.
//   -- أَتَظُنُّونَ (qs-v5-c08-003/004) fuses the interrogative hamza onto
//      the already-taught verb ظَنَّ ("to think") -- tagged 'part+impf.2mp',
//      extending the single-letter-proclitic-as-extra-atom pattern already
//      used for أَلِهَذَا (qasas-v3 ch8) to a plain verb form.
//   -- أَبَداً! أَبَداً! (qs-v5-c08-008/009) and إِنَّ ذَلِكَ لَا يَكُونُ! (twice,
//      -010/-011) are each kept as separate one-line sentence entries for
//      their printed repetition, matching the qasas-v3 ch8 precedent
//      (إِنَّ هَذَا لَظُلْمٌ عَظِيمٌ! kept as two identical entries) even though
//      here the repeated unit is a single word.
//   -- لَا تَزَالُونَ (qs-v5-c08-005/006/007) is the same كَانَ-sister family
//      as لَمْ يَزَلْ above (lemma زَالَ, "to cease"): negated with لَا, it
//      reads "you do not cease to be," i.e. "you will always remain/keep
//      on." This three-times-repeated frame, together with the four-times-
//      repeated أَتَظُنُّونَ..., is what the workshop below is built from.
//   -- زُرُوعٌ (qs-v5-c08-006/015, "crops, planted fields") and نَخِيلٌ
//      (qs-v5-c08-015, "palm trees") were both already taught in chapter 5
//      (qs-v5-c05-018, زَرْعٌ / نَخِيلٌ) -- chapter 5 precedes this one in
//      reading order, so both are reused here rather than re-listed as new,
//      even though this chapter's own sentences were drafted first. زَرْع is
//      the concrete noun (a crop/planting), distinct from the already-taught
//      abstract زِرَاعَة ("farming," ch1) despite sharing the root ز ر ع,
//      matching the corpus's established same-root-different-lemma
//      convention (نَصَحَ/نَصِيحَة/نَاصِح, qasas-v3 ch16). نَخِيل functions here as
//      a plain collective noun (grammatically singular despite denoting
//      plurality) -- no pl atom is given, the same way the already-taught
//      collective الْحَرْثُ ("cultivation," qasas-v3 ch16) carries none.
//   -- بُيُوتاً يَسْكُنُونَ فِيهَا (qs-v5-c08-016) is an indefinite noun
//      followed by a verbal clause functioning as its (relative-pronoun-
//      less) adjectival modifier -- "houses [that] they lived in" -- since
//      Arabic relative clauses on indefinite antecedents drop الَّذِي.
//   -- كُلَّ ذَلِكَ (qs-v5-c08-017/018) is tagged 'acc.constr' on كُلَّ,
//      matching the established tagging for كُلَّ + genitive/demonstrative
//      mudāf ilayh elsewhere in the corpus (qasas-v2/v3 كُلَّ شَيْءٍ-type
//      constructions); ذَلِكَ as mudāf ilayh keeps its ordinary
//      case-invariant demonstrative tag.
//   -- Shared lexicon check (CHAPTER-FORMAT.md §6): صَالِح (qasas-v5 ch4/5,
