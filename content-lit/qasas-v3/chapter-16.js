// Nūḥ calls his people and strives hard in counseling them, delivering
// Allah's warning word for word from the Qur'an (Sūrat Nūḥ 71:2-4):
// worship Allah, fear Him, obey His messenger, and He will forgive your
// sins and grant you respite until your appointed term -- but once
// Allah's appointed term comes, it cannot be delayed. Allah had already
// withheld the rain from the people and grown angry with them, crops and
// offspring growing scarce. So Nūḥ pleads with them directly: believe,
// and Allah will be pleased with you and lift this punishment, sending
// down rain and blessing you with provision and children. He calls them
// to Allah again and appeals to the signs around them -- the sky, the
// earth, the sun, the moon, the heavens, the earth spread like a carpet
// beneath them -- asking again and again who created all of it. But
// Nūḥ's people neither reason nor believe; whenever he calls them to
// Allah, they stop their ears with their fingers. The chapter closes on
// the narrator's own rhetorical question: how can one who will not hear,
// ever understand?
