// Nūḥ strives on and keeps calling his people for a thousand years save
// fifty, but they never believe, never abandon their idols, and never
// return to Allah. The narrator voices Nūḥ's mounting, unanswered
// question again and again -- how long must he watch the earth's
// corruption, stones worshipped, people eating Allah's provision while
// worshipping other than Him? -- before marveling that Nūḥ, after a
// thousand years less fifty of it, still does not grow angry: no one
// has ever endured patience like his. Allah then reveals to Nūḥ that no
// more of his people will ever believe beyond those who already have.
// When Nūḥ calls them once more, the people answer him in the Qur'an's
// own words (Sūrat Hūd 11:32): you have disputed with us long enough --
// now bring the punishment you keep promising, if you are telling the
// truth. Only then does Nūḥ finally grow angry for Allah's sake, despair
// of them, and pray: O Allah, do not leave a single disbeliever standing
// on the earth.
//
