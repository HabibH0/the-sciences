export const sourceRef = ref => typeof ref === 'number' ? { line: ref } : ref;
export function foundationGroups(lesson, conceptIndex) {
  const plan = foundationPlan(lesson);
  if (!plan) return null;
  const offset = plan.concepts.slice(0, conceptIndex).flat().length;
  return plan.concepts[conceptIndex].map((idea, i) => ({
    presentation: 'learn', lineIndices: idea.refs.map(ref => sourceRef(ref).line),
    foundationIndex: i, ideaIndex: offset + i, authoredVersion: 1,
  }));
}
